const bags = {};
const last = {};
function nextIndex(type) {
  const n = (LINES[type] || LINES.talk).length;
  let bag = bags[type];
  if (!bag || bag.length === 0) {
    bag = Array.from({ length: n }, (_, i) => i);
    for (let i = bag.length - 1; i > 0; i--) { const j = Math.floor(Math.random() * (i + 1)); [bag[i], bag[j]] = [bag[j], bag[i]]; }
    // не начинаем новый круг с той же фразы, которой закончили предыдущий
    if (bag.length > 1 && bag[0] === last[type]) [bag[0], bag[bag.length - 1]] = [bag[bag.length - 1], bag[0]];
  }
  bags[type] = bag;
  const idx = bag.pop();
  last[type] = idx;
  return idx;
}

export function pickLine(type, name = CHILD_NAME) {
  const arr = LINES[type] || LINES.talk;
  const raw = arr[nextIndex(type)];
  return { type, text: raw.replace(/\{name\}/g, name) };
}

// Для тапа по Тоботу: смешивание типов, чтобы он говорил разное, а не один и тот же набор.
const MIX = ['talk', 'talk', 'talk', 'joy', 'encourage', 'surprise', 'greeting'];
export function pickMixed(name = CHILD_NAME) {
  return pickLine(MIX[Math.floor(Math.random() * MIX.length)], name);
}
